/**
 * Geographic source data for the painted board bases.
 *
 * Why real geography: the map coordinates in `@pg/shared` are derived from each
 * city's true WGS84 lat/lon, normalised into [0.045, 0.955] on both axes. If we
 * paint a coastline from the same projection, every city lands where it should
 * — Hamburg on the Elbe, Cuxhaven on the estuary, San Francisco on the bay —
 * and the board reads as a real map instead of decorative noise.
 *
 * The projections below were recovered by fitting the published city
 * coordinates (verified to ~0.001 against Hamburg, Munich, Boston and
 * Los Angeles), so coastline and cities share one coordinate system exactly.
 *
 *   germany:  x = 0.4050 + (lon -   9.437) * 0.1061300
 *             y = 0.0450 + (54.783 - lat)  * 0.1278090
 *   usa:      x = 0.0511 + (lon + 122.332) * 0.0176300
 *             y = 0.0450 + (47.606 - lat)  * 0.0416830
 *
 * Outlines are hand-authored from national borders and coastlines at roughly
 * 30-50 km fidelity — enough that the silhouette is unmistakable, coarse enough
 * that it paints as an illustrated map rather than a GIS plot.
 */

export const PROJECTION = {
  germany: { x0: 0.405, lon0: 9.437, sx: 0.10613, y0: 0.045, lat0: 54.783, sy: 0.127809 },
  usa: { x0: 0.0511, lon0: -122.332, sx: 0.01763, y0: 0.045, lat0: 47.606, sy: 0.041683 },
};

/** Projects [lat, lon] pairs into the map's normalised [0,1] space. */
export function project(mapId, pts) {
  const p = PROJECTION[mapId];
  return pts.map(([lat, lon]) => [p.x0 + (lon - p.lon0) * p.sx, p.y0 + (p.lat0 - lat) * p.sy]);
}

